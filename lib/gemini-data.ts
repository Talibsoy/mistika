export function getDailyEnergy(date: Date = new Date()) {
  const start = new Date(date.getFullYear(), 0, 0);
  const dayOfYear = Math.floor((date.getTime() - start.getTime()) / 86400000);
  return DAILY_ENERGIES[dayOfYear % DAILY_ENERGIES.length];
}

export type DailyEnergy = (typeof DAILY_ENERGIES)[0];

export function calcLifePathNumber(dateStr: string): number {
  const digits = dateStr.replace(/\D/g, "");
  let sum = digits.split("").reduce((a, b) => a + parseInt(b), 0);
  while (sum > 9 && sum !== 11 && sum !== 22 && sum !== 33) {
    sum = sum.toString().split("").reduce((a, b) => a + parseInt(b), 0);
  }
  return sum;
}
